export const DICT: Record<Lang, Record<TranslationKey, string>> = { de, en };

/**
 * Looks up a key and fills `{placeholders}`. Falls back to German rather than
 * to the raw key: a missing English string should read as untranslated copy,
 * never as debug output in front of a buyer.
 */
export function t(
  lang: Lang,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const template = DICT[lang][key] ?? DICT.de[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/** Curried form for components that hold the language once. */
export function translator(lang: Lang) {
  return (key: TranslationKey, vars?: Record<string, string | number>) => t(lang, key, vars);
}
