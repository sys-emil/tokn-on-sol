/**
 * Buyer-facing translations (German and English).
 *
 * **No locale prefix in the URL.** An `app/[locale]/` restructure would clash
 * with the root dynamic segment `src/app/[handle]/page.tsx` — `/en` and
 * `/@name` are the same shape, and routing cannot tell them apart. The
 * language therefore lives in the `passly_lang` cookie, read server-side in
 * the root layout and handed to client components through LangProvider.
 *
 * Price of that choice: English pages are not separately indexable. Retrofit
 * with a middleware rewrite if EN SEO ever matters.
 *
 * Scope is deliberately the **buyer** surfaces. Dashboard, doorman, admin and
 * the legal texts stay German: they are read by German organizers, and a
 * half-translated legal page is worse than a German one.
 *
 * This module is imported by client components; keep it free of `next/headers`
 * and of any server-only dependency.
 */

export type Lang = "de" | "en";

export const LANGS: readonly Lang[] = ["de", "en"];
export const DEFAULT_LANG: Lang = "de";
export const LANG_COOKIE = "passly_lang";
/** One year; the choice is a preference, not a session. */
export const LANG_COOKIE_MAX_AGE = 60 * 60 * 24 * 365;

export function normalizeLang(value: string | null | undefined): Lang {
  return value === "en" ? "en" : "de";
}

/** Best-effort language from an Accept-Language header, for e-mail fallbacks. */
export function langFromAcceptLanguage(header: string | null | undefined): Lang {
  if (!header) return DEFAULT_LANG;
  const first = header.split(",")[0]?.trim().toLowerCase() ?? "";
  return first.startsWith("en") ? "en" : "de";
}

